await goTo(C, cl); await until(C, () => !!document.querySelector('#hide:not(.hidden)'), null, 20000); await C.keyboard.press('KeyE');
check(await until(C, () => bb.player.hidden, null, 20000), 'once Bobby is out, Cara can hide there');
await C.keyboard.press('KeyE'); await until(C, () => !bb.player.hidden, null, 15000); await until(B, () => [...bb.MP.others.values()].every(o => !o.hidden), null, 20000);
// both at the same moment: the host lets exactly one of them in
await goTo(B, cl); await goTo(C, cl); await B.waitForTimeout(1500);
await Promise.all([B.evaluate(() => bb.toggleHide()), C.evaluate(() => bb.toggleHide())]);
