const kicked = await A.evaluate(() => { const li = [...document.querySelectorAll('#lbList li')].find(l => l.textContent.includes('Dan')); const k = li && li.querySelector('.kick'); if (k) k.click(); return !!k; });
check(kicked, 'host has a kick button for Dan');
check(await until(D, () => /removed/i.test(document.getElementById('mpStatus').textContent)), 'Dan is back at the menu, told he was removed', await text(D, 'mpStatus'));
check(await until(A, () => document.querySelectorAll('#lbList li:not(.empty)').length === 3), 'host lists 3 players after the kick');
await D.context().close();
check(await until(B, () => document.querySelectorAll('#lbList li:not(.empty)').length === 3), 'others see the kick too');
check(!(await B.evaluate(() => !!document.querySelector('#lbList .kick'))), 'a non-owner has no kick buttons');
console.log('== nametag');
await fill(B, '#lbName', 'Bobby');
check(await until(A, () => [...document.querySelectorAll('#lbList .nm')].some(e => e.textContent.includes('Bobby'))), 'host sees the new nametag "Bobby"');
check(await until(C, () => [...document.querySelectorAll('#lbList .nm')].some(e => e.textContent.includes('Bobby'))), 'others see "Bobby" too');
console.log('== ready up');
await click(A, '#lbReady'); await click(B, '#lbReady');
await A.waitForTimeout(4500);
check(await A.evaluate(() => bb.state) === 'lobby', 'no start while Cara is not ready');
check(/2 of 3 ready/.test(await text(C, 'lbStatus')), 'status shows 2 of 3 ready', await text(C, 'lbStatus'));
await click(C, '#lbReady');
check(await until(C, () => /Starting in/.test(document.getElementById('lbStatus').textContent), null, 5000), 'countdown starts when everyone is ready');
const started = await Promise.all([A, B, C].map(P => until(P, () => bb.state === 'play' && bb.MP.inGame, null, 20000)));
check(started.every(Boolean), 'the game starts for all 3 players', started);
const grids = await Promise.all([A, B, C].map(P => P.evaluate(() => bb.grid.map(r => r.join('')).join('|'))));
check(grids[0] === grids[1] && grids[1] === grids[2], 'everyone got the same house');
const pos = await Promise.all([A, B, C].map(P => P.evaluate(() => [bb.player.x, bb.player.y])));
check(pos.every(([x, y]) => x > 50 && x < 200 && y > 50 && y < 200), 'everyone spawned in the start room', pos);
const dmin = Math.min(...[[0, 1], [0, 2], [1, 2]].map(([i, j]) => Math.hypot(pos[i][0] - pos[j][0], pos[i][1] - pos[j][1])));
check(dmin >= 22, 'nobody spawned inside someone else', dmin);
const fz = await A.evaluate(() => bb.fuses.length), fzB = await B.evaluate(() => bb.fuses.length);
check(fz === 5 && fzB === 5, '3 players: 5 fuses on floor 1 (3 + 2 extra)', [fz, fzB]);

// ---------------- in the game ----------------
const ids = await A.evaluate(() => ({ A: bb.MP.myId, others: [...bb.MP.others.values()].map(o => [o.name, o.id]) }));
const idOf = n => (ids.others.find(o => o[0].startsWith(n)) || [])[1];
const Bid = idOf('Bob'), Cid = idOf('Cara');
const freeze = () => A.evaluate(() => { bb.monster.active = false; bb.monster.spawnT = 1e9; });
await freeze();
console.log('== teammates');
check(await A.evaluate(() => [...bb.MP.others.values()].every(o => o.av && o.av.human)), 'teammates are human figures (not the simple stand-in)');
for (const P of [A, B, C]) check(await P.evaluate(() => [...bb.MP.others.values()].filter(o => o.av && o.av.obj.parent).length === 2), P.pname + ' sees 2 teammate figures in the world');
// Alice looks at the other two and takes a picture
await A.evaluate(() => { const o = [...bb.MP.others.values()]; const mx = (o[0].x + o[1].x) / 2, my = (o[0].y + o[1].y) / 2;
  bb.player.x = 75; bb.player.y = 125; bb.player.ang = Math.atan2(my - 125, mx - 75); bb.player.pitch = -0.05; });
await B.evaluate(() => { bb.player.x = 175; bb.player.y = 81; bb.player.ang = Math.PI; });
await C.evaluate(() => { bb.player.x = 181; bb.player.y = 175; bb.player.ang = Math.PI * 0.9; });
await until(A, () => [...bb.MP.others.values()].every(o => Math.hypot(o.x - o.tx, o.y - o.ty) < 3), null, 20000); await A.waitForTimeout(1500); await A.screenshot({ timeout: 120000, path: OUT + '/game_teammates.png' });
const seen = await A.evaluate(() => [...bb.MP.others.values()].map(o => [o.name, Math.round(o.x), Math.round(o.y)]));
check(seen.some(([n, x, y]) => n.startsWith('Bob') && Math.abs(x - 175) < 6 && Math.abs(y - 81) < 6), "the host sees Bobby where Bobby's own game says he is", seen);
console.log('== her position is the same for everyone');
await A.evaluate(() => { const m = bb.monster; m.active = true; m.spawnT = 0; m.state = 'wander'; m.target = null; });
await until(B, () => bb.monster.active, null, 30000); await A.waitForTimeout(2000);
const [mA, mB] = await Promise.all([A.evaluate(() => [bb.monster.x, bb.monster.y]), B.evaluate(() => [bb.monster.x, bb.monster.y, bb.monster.active])]);
check(mB[2] && Math.hypot(mA[0] - mB[0], mA[1] - mB[1]) < 40, 'a joiner sees her at the host\'s position', { mA, mB });
await freeze();
console.log('== body blocking');
await B.evaluate(() => { bb.player.x = 175; bb.player.y = 125; });
await C.evaluate(() => { bb.player.x = 75; bb.player.y = 181; });
await A.evaluate(() => { bb.player.x = 75; bb.player.y = 125; bb.player.ang = 0; bb.player.pitch = 0; });
await A.waitForTimeout(1500);
await A.keyboard.down('KeyW'); await A.waitForTimeout(4000); await A.keyboard.up('KeyW');
const blk = await A.evaluate(() => { const o = [...bb.MP.others.values()].find(q => q.name.startsWith('Bob')); return [bb.player.x, bb.player.y, o.x, o.y]; });
const dBlk = Math.hypot(blk[0] - blk[2], blk[1] - blk[3]);
check(blk[0] > 95, 'Alice walked towards Bobby', blk);   // (from x = 75; on a slow test machine she covers less ground in 4 s)
check(dBlk >= 20, 'Alice stopped at Bobby instead of walking through him (distance ' + dBlk.toFixed(1) + ')', blk);
console.log('== one person per wardrobe');
const cl = await A.evaluate(() => { const c = bb.closets[0]; return { x: c.x + c.ox * 10, y: c.y + c.oy * 10, ang: Math.atan2(-c.oy, -c.ox) }; });
const goTo = (P, q) => P.evaluate(q => { bb.player.x = q.x; bb.player.y = q.y; bb.player.ang = q.ang; }, q);
await goTo(B, cl); await B.waitForTimeout(1500); await B.keyboard.press('KeyE');
await until(B, () => !!document.querySelector('#hide:not(.hidden)'), null, 20000);
if (!(await B.evaluate(() => bb.player.hidden))) await B.keyboard.press('KeyE');
check(await until(B, () => bb.player.hidden, null, 20000), 'Bobby hides in the wardrobe');
await until(C, () => [...bb.MP.others.values()].some(o => o.hidden), null, 20000);
await A.waitForTimeout(1000);
await goTo(C, cl); await until(C, () => !!document.querySelector('#hide:not(.hidden)'), null, 20000); await C.keyboard.press('KeyE'); await until(C, () => /locked/i.test(document.getElementById('msg').textContent), null, 15000);
